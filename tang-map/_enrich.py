# -*- coding: utf-8 -*-
import io

P = 'data/dynasties.js'
s = io.open(P, encoding='utf-8').read()

def esc(x):
    return x.replace('\\', '\\\\').replace('"', '\\"')

def put_card(title, **kw):
    global s
    key = '{t:"' + title + '"'
    assert key in s, 'missing card ' + title
    parts = []
    for k in ("life", "alias", "rel", "to", "end"):
        if k in kw:
            v = kw[k]
            parts.append('%s:%s' % (k, v if isinstance(v, int) else '"' + esc(str(v)) + '"'))
    assert parts
    s = s.replace(key, key + ', ' + ", ".join(parts), 1)

def put_emp(name, pname, **kw):
    global s
    key = '{n:"' + name + '", p:"' + pname + '"'
    assert key in s, 'missing emp ' + name + '/' + pname
    parts = []
    for k in ("life", "alias", "rel"):
        if k in kw:
            parts.append('%s:"%s"' % (k, esc(kw[k])))
    s = s.replace(key, key + ', ' + ", ".join(parts), 1)

